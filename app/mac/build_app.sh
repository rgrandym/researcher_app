#!/usr/bin/env bash
# Build Research.app (in /Applications if it is already there, else ~/Applications), with its icon, ready to drag to the Dock.
#
#   bash app/mac/build_app.sh
#
# 1. Activates the app's conda env (scripts/env.sh: creates it, installs the packages,
#    updates the agent CLIs), then resolves python, claude, node, code and pandoc and
#    writes their absolute paths to app/data/paths.json: an app started from the Dock does not get the shell's
#    PATH. Codex is found by the backend at each start instead, because its folder moves
#    with every VS Code extension update.
# 2. Builds the front end.
# 3. Writes the bundle: an AppleScript application (osacompile) with the .icns icon made
#    by sips and iconutil, signed ad hoc; all three ship with macOS. A compiled app,
#    unlike a bare shell script, can ask macOS for access to the Desktop folder where
#    this workspace lives, and the processes it starts share that access. It runs
#    mac/start.sh, stays in the Dock while the app runs, and quits when it stops.
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Rebuild in place wherever Research.app already is (so a Dock item keeps working);
# otherwise ~/Applications.
if [[ -z "${DEST:-}" ]]; then
  if [[ -d /Applications/Research.app ]]; then DEST=/Applications; else DEST="$HOME/Applications"; fi
fi
BUNDLE="$DEST/Research.app"
log() { printf '\033[1;34m[build]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[build]\033[0m %s\n' "$*" >&2; }

# ------------------------------------------------------------------ 1. binaries
mkdir -p "$APP_DIR/data"
# The app's conda env, created or synced, with Claude Code and Codex updated.
# shellcheck disable=SC1091
source "$APP_DIR/scripts/env.sh"
missing=()
resolve() { command -v "$1" 2>/dev/null || true; }
PY="$(resolve python)"; CLAUDE="$(resolve claude)"; NODE="$(resolve node)"; CODE="$(resolve code)"; PANDOC="$(resolve pandoc)"
[[ -z "$PY" ]] && { warn "python3 not found"; exit 1; }
for pair in "claude:$CLAUDE" "node:$NODE" "code:$CODE" "pandoc:$PANDOC"; do
  [[ -z "${pair#*:}" ]] && missing+=("${pair%%:*}")
done
"$PY" - "$APP_DIR/data/paths.json" "$PY" "$CLAUDE" "$NODE" "$CODE" "$PANDOC" <<'EOF'
import json, sys
out, py, claude, node, code, pandoc = sys.argv[1:]
paths = {k: v for k, v in {"python3": py, "claude": claude, "node": node, "code": code, "pandoc": pandoc}.items() if v}
open(out, "w").write(json.dumps(paths, indent=2) + "\n")
EOF
log "Paths written to app/data/paths.json (python3: $PY)"
if ((${#missing[@]})); then warn "Not found on PATH: ${missing[*]}. Those features will be unavailable."; fi
"$PY" -c "import fastapi, uvicorn, pydantic" 2>/dev/null || { warn "This Python lacks fastapi/uvicorn/pydantic: $PY -m pip install fastapi uvicorn pydantic"; exit 1; }
[[ -d "/Applications/Google Chrome.app" ]] || warn "Google Chrome not found; the app will open in your default browser."

# ------------------------------------------------------------------ 2. front end
command -v npm >/dev/null || { warn "npm not found"; exit 1; }
log "Building the front end"
(cd "$APP_DIR/web" && { [[ -d node_modules ]] || npm install --no-audit --no-fund; } && npm run build >/dev/null)

# ------------------------------------------------------------------ 3. the bundle
WORK="$(mktemp -d)"
cat > "$WORK/Research.applescript" <<EOF
-- Generated by app/mac/build_app.sh. The app's logic is in mac/start.sh.
property startScript : "$APP_DIR/mac/start.sh"
property launchedAt : 0

on run
	startApp()
end run

-- Clicking the Dock icon while the app runs brings its window up and to the front, as any
-- app does, and opens nothing new. Un-minimise the window (System Events; macOS asks once
-- for Accessibility permission, and without it the window is still raised but stays in the
-- Dock), then activate its Chrome process (start.sh --raise). Only when no window is open
-- does a click open one.
on reopen
	set pid to ""
	try
		set pid to do shell script "/bin/bash " & quoted form of startScript & " --window-pid"
	end try
	if pid is "" then
		startApp()
		return
	end if
	try
		tell application "System Events" to tell (first process whose unix id is (pid as integer))
			set value of attribute "AXMinimized" of every window to false
		end tell
	end try
	try
		do shell script "/bin/bash " & quoted form of startScript & " --raise"
	end try
end reopen

on startApp()
	set launchedAt to (current date)
	do shell script "/bin/bash " & quoted form of startScript & " > /dev/null 2>&1 &"
end startApp

on appStatus()
	try
		return do shell script "/bin/bash " & quoted form of startScript & " --status"
	on error
		return "down"
	end try
end appStatus

-- Leave the Dock once the app has stopped (the window was closed).
on idle
	if ((current date) - launchedAt) > 20 and appStatus() is "down" then quit
	return 5
end idle

on quit
	set s to appStatus()
	if s is "turn" then
		set answer to button returned of (display dialog "An agent turn is still running. Stop it, or keep it running in the background?" buttons {"Keep running", "Stop it"} default button "Keep running" with title "Research")
		if answer is "Stop it" then do shell script "/bin/bash " & quoted form of startScript & " --stop"
	else if s is "up" then
		do shell script "/bin/bash " & quoted form of startScript & " --stop"
	end if
	continue quit
end quit
EOF

# macOS keeps a permission (Accessibility, Desktop access) only while the app's code
# identity holds. Two things keep it from changing: an app whose contents did not change
# is left exactly as it is, and the app is signed with a stable local certificate, so a
# rebuilt app keeps its identity too. (An ad-hoc signature is a hash of the files: every
# rebuild was a new app to macOS, which asked for its permissions again.)
BUILD_FORMAT=2
STAMP="$( { echo "$BUILD_FORMAT"; cat "$WORK/Research.applescript" "$APP_DIR/mac/icon.png"; } | shasum -a 256 | cut -d' ' -f1)"
SIGNER="Research Local Signing"
if [[ -d "$BUNDLE" && "$(cat "$BUNDLE/Contents/Resources/build-stamp" 2>/dev/null)" == "$STAMP" ]] \
  && codesign -dr - "$BUNDLE" 2>&1 | grep -q "certificate leaf" \
  && codesign --verify --deep --strict "$BUNDLE" 2>/dev/null; then
  rm -rf "$WORK"
  log "Research.app is unchanged: left as it is, so macOS keeps its permissions."
  exit 0
fi

ensure_signer() {
  security find-identity -p codesigning 2>/dev/null | grep -q "\"$SIGNER\"" && return 0
  log "Creating the local signing certificate \"$SIGNER\" (once; it stays in your login keychain)"
  local d ok
  d="$(mktemp -d)"
  printf '%s\n' '[req]' 'distinguished_name = dn' 'prompt = no' 'x509_extensions = ext' '[dn]' \
    "CN = $SIGNER" '[ext]' 'basicConstraints = critical,CA:false' \
    'keyUsage = critical,digitalSignature' 'extendedKeyUsage = critical,codeSigning' > "$d/cert.cnf"
  /usr/bin/openssl req -x509 -newkey rsa:2048 -nodes -keyout "$d/key.pem" -out "$d/cert.pem" \
    -days 3650 -config "$d/cert.cnf" >/dev/null 2>&1 \
    && /usr/bin/openssl pkcs12 -export -inkey "$d/key.pem" -in "$d/cert.pem" -out "$d/id.p12" \
      -passout pass:research -name "$SIGNER" >/dev/null 2>&1 \
    && security import "$d/id.p12" -k "$HOME/Library/Keychains/login.keychain-db" -P research \
      -T /usr/bin/codesign >/dev/null 2>&1
  ok=$?
  rm -rf "$d"
  return $ok
}

log "Writing $BUNDLE"
rm -rf "$BUNDLE"
osacompile -s -o "$BUNDLE" "$WORK/Research.applescript"

ICONSET="$WORK/Research.iconset"
mkdir -p "$ICONSET"
for size in 16 32 128 256 512; do
  sips -z $size $size "$APP_DIR/mac/icon.png" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null
  double=$((size * 2))
  sips -z $double $double "$APP_DIR/mac/icon.png" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$BUNDLE/Contents/Resources/applet.icns"
rm -f "$BUNDLE/Contents/Resources/Assets.car"   # else macOS shows the generic applet icon

PLIST="$BUNDLE/Contents/Info.plist"
pb() { /usr/libexec/PlistBuddy -c "$1" "$PLIST" >/dev/null 2>&1 || true; }
pb "Delete :CFBundleIconName"
pb "Set :CFBundleName Research"
pb "Add :CFBundleDisplayName string Research"
pb "Set :CFBundleIdentifier local.research.launcher"
pb "Add :CFBundleIdentifier string local.research.launcher"
pb "Add :NSDesktopFolderUsageDescription string Research runs your research workspace, which is in your Desktop folder."
pb "Add :NSDocumentsFolderUsageDescription string Research opens files in your research workspace."
echo "$STAMP" > "$BUNDLE/Contents/Resources/build-stamp"
if ensure_signer && codesign --force --deep -s "$SIGNER" "$BUNDLE" 2>/dev/null; then
  log "Signed with \"$SIGNER\": permissions you grant survive later rebuilds."
else
  warn "The local certificate could not be used; signed ad hoc, so macOS may ask for permissions again after a rebuild."
  codesign --force --deep -s - "$BUNDLE" 2>/dev/null
fi
touch "$BUNDLE"
rm -rf "$WORK"

log "Done: $BUNDLE"
log "The first time it opens, macOS asks whether Research may access your Desktop folder."
log "Click OK: the workspace lives there. Then drag Research onto the Dock to keep it."
