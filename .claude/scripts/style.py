#!/usr/bin/env python3
"""Report styles: palettes, typography, and per-format style assets.

A style is one JSON file in .claude/styles/. This script turns it into whatever
the target format needs — CSS for HTML/PDF, a patched reference.docx for Word, a
patched reference.pptx for slides, a palette for the figure renderer.

    python3 .claude/scripts/style.py list
    python3 .claude/scripts/style.py show meridian
    python3 .claude/scripts/style.py css meridian --cover -o out/style.css
    python3 .claude/scripts/style.py docx-ref meridian -o out/reference.docx
    python3 .claude/scripts/style.py pptx-ref meridian -o out/reference.pptx
    python3 .claude/scripts/style.py swatch meridian -o out/meridian.png

Adding a style: copy any .claude/styles/*.json, change the values, done. No code
change is needed — every consumer reads the JSON. See .claude/styles/README.md.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

STYLE_DIR = Path(__file__).resolve().parent.parent / "styles"

REQUIRED_KEYS = ("name", "label", "fonts", "color", "series", "table", "chart")
REQUIRED_COLORS = ("ink", "body", "muted", "accent", "accent_soft", "rule",
                   "surface", "surface_alt", "link")
OPTIONAL_COLORS = ("mute_fill", "warn")   # fall back to `rule` / `muted` when absent


# ---------------------------------------------------------------- loading

def available():
    return sorted(p.stem for p in STYLE_DIR.glob("*.json"))


def load(name):
    """Load and validate a style. Unknown name → error listing the real ones."""
    if not name or name.lower() in ("none", "plain"):
        return None
    path = STYLE_DIR / f"{name}.json"
    if not path.exists():
        sys.exit(f"unknown style {name!r}; available: {', '.join(available())} (or 'none')")
    st = json.loads(path.read_text())
    missing = [k for k in REQUIRED_KEYS if k not in st]
    missing += [f"color.{k}" for k in REQUIRED_COLORS if k not in st.get("color", {})]
    if missing:
        sys.exit(f"{path.name} is missing: {', '.join(missing)}")
    if len(st["series"]) < 4:
        sys.exit(f"{path.name}: 'series' needs at least 4 colours")
    st.setdefault("sequential", [st["color"]["surface_alt"], st["color"]["accent"]])
    st.setdefault("diverging", st["sequential"])
    st.setdefault("page", {})
    st["page"].setdefault("size", "A4")
    st["page"].setdefault("margin_mm", [20, 18, 20, 18])
    st["page"].setdefault("cover", "rule")
    return st


def font_stack(names):
    return ", ".join(f'"{n}"' if " " in n else n for n in names)


def hexval(c):
    return c.lstrip("#").upper()


# ---------------------------------------------------------------- CSS

def build_css(st, cover=True):
    if st is None:
        return "/* style: none — pandoc defaults */\n"

    c, f, t = st["color"], st["fonts"], st["table"]
    pg = st["page"]
    mt, mr, mb, ml = pg["margin_mm"]
    base = f.get("base_pt", 10.5)
    zebra = t.get("zebra", "none")
    tstyle = t.get("style", "banded")
    rulew = t.get("rule_weight_pt", 0.6)
    heavy = f"{rulew * 2:.2f}pt"

    cover_css = ""
    if cover and pg.get("cover") != "off":
        band = {
            "band": f"border-top: 6pt solid {c['accent']}; border-bottom: 1pt solid {c['rule']};",
            "block": f"background: {c['accent_soft']}; padding: 22pt 18pt; border-left: 6pt solid {c['accent']};",
            "rule": f"border-bottom: {heavy} solid {c['accent']};",
            "minimal": f"border-bottom: 0.5pt solid {c['rule']};",
        }.get(pg.get("cover", "rule"), "")
        cover_css = f"""
/* cover / title block — its own page, so the document opens on the title */
#title-block-header {{
  {band}
  margin: 0 0 28pt; padding-bottom: 16pt;
  break-after: page; page-break-after: always;
  display: flex; flex-direction: column; justify-content: flex-end;
  min-height: 62vh;
}}
#title-block-header .title {{
  font-size: {base * 2.6:.1f}pt; line-height: 1.12; margin: 0 0 10pt;
  color: {c['ink']}; border: 0; padding: 0; text-align: left;
}}
#title-block-header .subtitle {{ font-size: {base * 1.25:.1f}pt; color: {c['muted']}; margin: 0 0 10pt; font-weight: 400; }}
#title-block-header .author,
#title-block-header .date {{
  font-family: {font_stack(f['heading'])}; font-size: {base * 0.8:.1f}pt;
  color: {c['muted']}; margin: 0.6em 0 0; text-align: left;
  letter-spacing: 0.04em; line-height: 1.5;
}}
"""

    return f"""/* ============================================================
   {st['label']} — generated by .claude/scripts/style.py
   {st.get('tagline', '')}
   Edit .claude/styles/{st['name']}.json, not this file.
   ============================================================ */

:root {{
  --ink: {c['ink']}; --body: {c['body']}; --muted: {c['muted']};
  --accent: {c['accent']}; --accent-soft: {c['accent_soft']};
  --rule: {c['rule']}; --mute-fill: {c.get('mute_fill', c['rule'])};
  --surface: {c['surface']}; --surface-alt: {c['surface_alt']};
{chr(10).join(f"  --series-{i + 1}: {s};" for i, s in enumerate(st['series']))}
}}

@page {{
  size: {pg['size']};
  margin: {mt}mm {mr}mm {mb}mm {ml}mm;
  @bottom-left {{
    content: string(doctitle);
    font-family: {font_stack(f['heading'])}; font-size: 7.5pt; color: {c['muted']};
  }}
  @bottom-right {{
    content: counter(page) " / " counter(pages);
    font-family: {font_stack(f['heading'])}; font-size: 7.5pt; color: {c['muted']};
  }}
}}
@page landscape {{ size: {pg['size']} landscape; }}
@page :first {{ @bottom-left {{ content: ""; }} @bottom-right {{ content: ""; }} }}

/* mark an oversized table or figure `.wide` to give it its own landscape page */
.wide {{ page: landscape; }}

/* magazine-style inset: an exhibit the text runs around rather than one that
   interrupts it. Use for a supplied illustration that a reader consults while
   reading, never for a data exhibit carrying a finding the prose depends on. */
.float-right, .float-left {{
  width: 54.7%; margin: 0.2em 0 1em 1.6em;
  break-inside: avoid; page-break-inside: avoid;
}}
.float-right {{ float: right; margin-right: 0; }}
.float-left  {{ float: left;  margin: 0.2em 1.6em 1em 0; }}
.float-right img, .float-left img {{ width: 100%; height: auto; }}
.float-right p, .float-left p {{ font-size: 0.86em; line-height: 1.35; }}

/* a floated inset never runs past its own section */
h1, h2, h3 {{ clear: both; }}

@media (max-width: 40em) {{
  .float-right, .float-left {{ float: none; width: 100%; margin: 1.2em 0; }}
}}

html {{ font-size: {base}pt; }}
body {{
  font-family: {font_stack(f['body'])};
  font-size: {base}pt; line-height: 1.5;
  color: {c['body']}; background: {c['surface']};
  max-width: 46em; margin: 0 auto; padding: 2rem 1.25rem 4rem;
  -webkit-font-smoothing: antialiased;
  hyphens: auto;
}}

h1, h2, h3, h4, h5, h6 {{
  font-family: {font_stack(f['heading'])};
  font-weight: {f.get('heading_weight', 600)};
  letter-spacing: {f.get('heading_tracking', '0')};
  color: {c['ink']};
  line-height: 1.22;
  break-after: avoid; page-break-after: avoid;
  text-wrap: balance;
}}
h1 {{ font-size: {base * 2.0:.1f}pt; margin: 0 0 0.6em; string-set: doctitle content(); }}
h2 {{
  font-size: {base * 1.35:.1f}pt; margin: 2.1em 0 0.55em;
  padding-bottom: 0.25em; border-bottom: {rulew}pt solid {c['rule']};
}}
h3 {{ font-size: {base * 1.1:.1f}pt; margin: 1.6em 0 0.4em; }}
h4 {{ font-size: {base:.1f}pt; margin: 1.3em 0 0.35em; color: {c['muted']}; text-transform: uppercase; letter-spacing: 0.07em; }}

p {{ margin: 0 0 0.85em; orphans: 2; widows: 2; }}
strong {{ color: {c['ink']}; font-weight: 700; }}
a {{ color: {c['link']}; text-decoration: none; border-bottom: 0.5pt solid {c['rule']}; }}
a[href^="http"]:after {{ content: ""; }}

/* the answer-first opening paragraph */
p.lead, body > p:first-of-type {{ font-size: {base * 1.1:.1f}pt; color: {c['ink']}; }}

/* callouts: blockquote is the confidence statement / key caveat */
blockquote {{
  margin: 1.2em 0; padding: 0.7em 1em;
  background: {c['accent_soft']}; border-left: 3pt solid {c['accent']};
  color: {c['ink']}; break-inside: avoid;
}}
blockquote p:last-child {{ margin-bottom: 0; }}

/* ---------------- tables ---------------- */
table {{
  width: 100%; border-collapse: collapse;
  margin: 1.2em 0; font-size: {base * 0.86:.1f}pt;
  table-layout: fixed; word-wrap: break-word; overflow-wrap: anywhere;
  break-inside: auto;
}}
caption {{
  caption-side: top; text-align: left;
  font-family: {font_stack(f['heading'])}; font-size: {base * 0.86:.1f}pt;
  font-weight: 600; color: {c['ink']}; padding-bottom: 0.4em;
}}
thead {{ display: table-header-group; }}
tr {{ break-inside: avoid; page-break-inside: avoid; }}
th {{
  font-family: {font_stack(f['heading'])}; font-weight: 600; text-align: left;
  background: {t['header_bg'] if tstyle != 'rules' else 'transparent'};
  color: {t['header_fg']};
  padding: 0.45em 0.6em; vertical-align: bottom;
  border-bottom: {heavy} solid {c['ink'] if tstyle == 'rules' else t['border']};
}}
td {{ padding: 0.4em 0.6em; vertical-align: top; border-bottom: {rulew}pt solid {t['border']}; }}
{f"tbody tr:nth-child(even) td {{ background: {zebra}; }}" if zebra and zebra != "none" else "/* no zebra banding in this style */"}
td:not(:first-child), th:not(:first-child) {{ text-align: left; }}
.num td, td.num, th.num {{ text-align: right; font-variant-numeric: tabular-nums; }}

/* ---------------- figures ---------------- */
figure {{ margin: 1.4em 0; break-inside: avoid; page-break-inside: avoid; text-align: left; }}
figure img, img {{ max-width: 100%; height: auto; }}
figcaption {{
  font-family: {font_stack(f['heading'])}; font-size: {base * 0.82:.1f}pt;
  color: {c['muted']}; margin-top: 0.45em; line-height: 1.4;
}}
figcaption strong {{ color: {c['ink']}; }}

/* ---------------- code / confidence block ---------------- */
pre {{
  font-family: {font_stack(f['mono'])}; font-size: {base * 0.8:.1f}pt;
  background: {c['surface_alt']}; border: 0.5pt solid {c['rule']};
  border-left: 3pt solid {c['accent']};
  padding: 0.8em 1em; overflow-x: auto; break-inside: avoid; line-height: 1.45;
}}
code {{ font-family: {font_stack(f['mono'])}; font-size: 0.88em; }}

/* ---------------- table of contents ---------------- */
#TOC {{
  border: 0.5pt solid {c['rule']}; background: {c['surface_alt']};
  padding: 1em 1.2em 1em 0.6em; margin: 0 0 2em; break-after: page;
  font-family: {font_stack(f['heading'])}; font-size: {base * 0.9:.1f}pt;
}}
#TOC ul {{ list-style: none; padding-left: 1.1em; margin: 0; }}
#TOC > ul {{ padding-left: 0.6em; }}
#TOC a {{ border: 0; color: {c['ink']}; }}
#TOC ul ul a {{ color: {c['muted']}; }}

/* ---------------- sources ---------------- */
#sources p, #sources li {{
  font-size: {base * 0.84:.1f}pt; color: {c['muted']};
  padding-left: 1.6em; text-indent: -1.6em; margin-bottom: 0.35em;
  overflow-wrap: anywhere;
}}
#sources a {{ border: 0; }}

hr {{ border: 0; border-top: {rulew}pt solid {c['rule']}; margin: 2em 0; }}
{cover_css}
@media print {{ body {{ max-width: none; padding: 0; }} }}
"""


# ---------------------------------------------------------------- docx

def _patch_theme_xml(xml, st):
    c, f = st["color"], st["fonts"]
    ser = (st["series"] + st["series"])[:6]
    for tag, val in [("dk2", c["ink"]), ("lt2", c["surface_alt"]),
                     ("hlink", c["link"]), ("folHlink", c["muted"])] + \
                    [(f"accent{i + 1}", s) for i, s in enumerate(ser)]:
        xml = re.sub(rf"(<a:{tag}>\s*<a:srgbClr val=\")[0-9A-Fa-f]{{6}}",
                     lambda m, v=val: m.group(1) + hexval(v), xml)
    # dk1 is sysClr windowText in the default theme; it drives body text
    xml = re.sub(r"<a:dk1>\s*<a:sysClr[^/]*/>\s*</a:dk1>",
                 f'<a:dk1><a:srgbClr val="{hexval(c["body"])}"/></a:dk1>', xml)
    head, body = f["heading"][0], f["body"][0]
    xml = re.sub(r'(<a:majorFont>\s*<a:latin typeface=")[^"]*"[^/]*/>',
                 rf'\g<1>{head}"/>', xml, count=1)
    xml = re.sub(r'(<a:minorFont>\s*<a:latin typeface=")[^"]*"[^/]*/>',
                 rf'\g<1>{body}"/>', xml, count=1)
    return xml


def _patch_styles_xml(xml, st):
    c, f, t = st["color"], st["fonts"], st["table"]
    half = int(round(f.get("base_pt", 10.5) * 2))

    # default body size
    xml = re.sub(r'(<w:rPrDefault>\s*<w:rPr>.*?)<w:sz w:val="\d+" />\s*<w:szCs w:val="\d+" />',
                 rf'\g<1><w:sz w:val="{half}" /><w:szCs w:val="{half}" />', xml, flags=re.S)

    scale = {"Title": 2.6, "Subtitle": 1.3, "Heading1": 1.7, "Heading2": 1.32,
             "Heading3": 1.12, "Heading4": 1.0, "Heading5": 0.95, "Heading6": 0.9}
    colors = {"Title": c["ink"], "Subtitle": c["muted"], "Heading1": c["ink"],
              "Heading2": c["accent"], "Heading3": c["ink"], "Heading4": c["muted"],
              "Heading5": c["muted"], "Heading6": c["muted"]}

    def fix(m):
        sid, block = m.group(1), m.group(0)
        if sid not in scale:
            return block
        sz = int(round(f.get("base_pt", 10.5) * 2 * scale[sid]))
        col = f'<w:color w:val="{hexval(colors[sid])}" />'
        if "<w:color " in block:
            block = re.sub(r'<w:color [^/]*/>', col, block, count=1)
        elif "<w:rPr>" in block:
            block = block.replace("<w:rPr>", f"<w:rPr>{col}", 1)
        block = re.sub(r'<w:sz w:val="\d+" />', f'<w:sz w:val="{sz}" />', block)
        block = re.sub(r'<w:szCs w:val="\d+" />', f'<w:szCs w:val="{sz}" />', block)
        if sid.startswith("Heading") and "<w:b " not in block and "<w:rPr>" in block:
            block = block.replace("<w:rPr>", '<w:rPr><w:b w:val="1" />', 1)
        return block

    xml = re.sub(r'<w:style w:type="paragraph"[^>]*w:styleId="([A-Za-z0-9]+)"[^>]*>.*?</w:style>',
                 fix, xml, flags=re.S)

    xml = re.sub(r'(<w:style w:type="character" w:styleId="Hyperlink">.*?<w:color )[^/]*/>',
                 rf'\g<1>w:val="{hexval(c["link"])}" />', xml, flags=re.S)

    # table style: header shading + banding, driven by the style's table block
    header_fill = hexval(t["header_bg"])
    header_fg = hexval(t["header_fg"])
    band = t.get("zebra", "none")
    sz8 = max(2, int(round(t.get("rule_weight_pt", 0.6) * 8)))
    tbl = """<w:tblStylePr w:type="firstRow"><w:rPr><w:b w:val="1" />"""
    tbl += f"""<w:color w:val="{header_fg}" /></w:rPr><w:tcPr>"""
    if t.get("style") != "rules":
        tbl += f"""<w:shd w:val="clear" w:color="auto" w:fill="{header_fill}" />"""
    tbl += f"""<w:tcBorders><w:bottom w:val="single" w:sz="{sz8 * 2}" w:color="{hexval(t['border'])}" /></w:tcBorders>"""
    tbl += """<w:vAlign w:val="bottom" /></w:tcPr></w:tblStylePr>"""
    if band and band != "none":
        tbl += (f'<w:tblStylePr w:type="band1Horz"><w:tcPr><w:shd w:val="clear" '
                f'w:color="auto" w:fill="{hexval(band)}" /></w:tcPr></w:tblStylePr>')
    xml = re.sub(r'<w:tblStylePr w:type="firstRow">.*?</w:tblStylePr>', tbl, xml, flags=re.S)
    return xml


def _rezip(src, dst, patches):
    """Copy an OOXML package, replacing the named members."""
    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(src) as zin, zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename in patches:
                data = patches[item.filename](data.decode("utf-8")).encode("utf-8")
            zout.writestr(item, data)
    return dst


def _default_data_file(name, tmp):
    out = Path(tmp) / name
    with open(out, "wb") as fh:
        subprocess.run(["pandoc", "--print-default-data-file", name],
                       stdout=fh, check=True)
    return out


def docx_ref(st, out):
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        src = _default_data_file("reference.docx", tmp)
        if st is None:
            return shutil.copy(src, out)
        return _rezip(src, out, {
            "word/styles.xml": lambda x: _patch_styles_xml(x, st),
            "word/theme/theme1.xml": lambda x: _patch_theme_xml(x, st),
        })


def pptx_ref(st, out):
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        src = _default_data_file("reference.pptx", tmp)
        if st is None:
            return shutil.copy(src, out)
        with zipfile.ZipFile(src) as z:
            themes = [n for n in z.namelist() if re.match(r"ppt/theme/theme\d+\.xml$", n)]
        return _rezip(src, out, {n: (lambda x: _patch_theme_xml(x, st)) for n in themes})


# ---------------------------------------------------------------- swatch

def swatch(st, out):
    """Render a one-image preview of the palette — for choosing a style."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle

    c = st["color"]
    fig, ax = plt.subplots(figsize=(7.2, 2.5), dpi=200)
    ax.set_xlim(0, 12); ax.set_ylim(0, 4.2); ax.axis("off")
    fig.patch.set_facecolor(c["surface"])

    ax.text(0.1, 3.75, st["label"], fontsize=17, color=c["ink"], weight="bold")
    ax.text(0.1, 3.3, st.get("tagline", ""), fontsize=7.5, color=c["muted"])

    for i, col in enumerate(st["series"][:8]):
        ax.add_patch(Rectangle((0.1 + i * 1.48, 1.85), 1.35, 0.95, color=col))
        ax.text(0.1 + i * 1.48, 1.62, col.upper(), fontsize=5.2, color=c["muted"], family="monospace")
    ax.text(0.1, 2.95, "SERIES", fontsize=6, color=c["muted"])

    for i, col in enumerate(st["sequential"]):
        w = 11.8 / len(st["sequential"])
        ax.add_patch(Rectangle((0.1 + i * w, 0.75), w, 0.45, color=col))
    ax.text(0.1, 1.28, "SEQUENTIAL", fontsize=6, color=c["muted"])

    for i, col in enumerate(st["diverging"]):
        w = 11.8 / len(st["diverging"])
        ax.add_patch(Rectangle((0.1 + i * w, 0.12), w, 0.45, color=col))
    ax.text(0.1, 0.65, "DIVERGING", fontsize=6, color=c["muted"])

    Path(out).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, bbox_inches="tight", facecolor=c["surface"])
    plt.close(fig)
    return out


# ---------------------------------------------------------------- cli

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    for cmd in ("show", "css", "docx-ref", "pptx-ref", "swatch"):
        p = sub.add_parser(cmd)
        p.add_argument("style")
        p.add_argument("-o", "--out")
        if cmd == "css":
            p.add_argument("--cover", action="store_true", help="style the title block as a cover page")
    a = ap.parse_args()

    if a.cmd == "list":
        for n in available():
            st = load(n)
            print(f"{st['label']:<10} ({n:<9}) {st.get('tagline','')}")
            print(f"{'':<22}best for: {st.get('best_for','—')}")
        print(f"{'None':<10} (none     ) pandoc defaults, no styling")
        return

    st = load(a.style)
    if a.cmd == "show":
        print(json.dumps(st, indent=2))
    elif a.cmd == "css":
        css = build_css(st, cover=getattr(a, "cover", False))
        if a.out:
            Path(a.out).parent.mkdir(parents=True, exist_ok=True)
            Path(a.out).write_text(css)
            print(a.out)
        else:
            print(css)
    elif a.cmd in ("docx-ref", "pptx-ref"):
        out = a.out or f"reference.{a.cmd[:4]}"
        (docx_ref if a.cmd == "docx-ref" else pptx_ref)(st, out)
        print(out)
    elif a.cmd == "swatch":
        print(swatch(st, a.out or f"{a.style}.png"))


if __name__ == "__main__":
    main()
